/**
 * The service worker source. It is plain JavaScript in a string because the
 * worker is not part of the page bundle: the Vite plugin writes it beside the
 * assets with the build's ID and precache list filled in.
 *
 * The worker never calls `skipWaiting` on install. A new worker waits until
 * the page asks for it, which is how the player chooses when to update.
 */

const BUILD_ID = '__QUORUM_BUILD_ID__'
const PRECACHE = '__QUORUM_PRECACHE__'

const SOURCE = String.raw`/* Quorum service worker. Generated by apps/web/pwa/plugin.ts. */
const BUILD = '__QUORUM_BUILD_ID__'
const PRECACHE = __QUORUM_PRECACHE__
const CACHE = 'quorum-' + BUILD
/* The server owns these paths; the helper page and the worker itself must stay live. */
const SERVER = /^\/(?:api|q|mcp)(?:\/|$)/
/* Hashed code and the art load on first use and stay for the next visit. */
const RUNTIME = /^\/(?:assets|art)\//
/* A static response may carry Vary: Origin, and the precache was fetched without one.
   The shell is hashed and same-origin, so the header cannot change what it holds. */

self.addEventListener('install', function (event) {
  event.waitUntil(
    caches.open(CACHE).then(function (cache) {
      return cache.addAll(PRECACHE)
    }),
  )
})

self.addEventListener('activate', function (event) {
  event.waitUntil(
    caches
      .keys()
      .then(function (keys) {
        return Promise.all(
          keys
            .filter(function (key) {
              return key.indexOf('quorum-') === 0 && key !== CACHE
            })
            .map(function (key) {
              return caches.delete(key)
            }),
        )
      })
      .then(function () {
        return self.clients.claim()
      }),
  )
})

self.addEventListener('message', function (event) {
  if (event.data && event.data.type === 'SKIP_WAITING') self.skipWaiting()
})

function bypass(request, url) {
  if (request.method !== 'GET') return true
  if (url.origin !== self.location.origin) return true
  if (SERVER.test(url.pathname)) return true
  return url.pathname === '/sw.js' || url.pathname === '/harness.html'
}

self.addEventListener('fetch', function (event) {
  const request = event.request
  const url = new URL(request.url)
  if (bypass(request, url)) return

  if (request.mode === 'navigate') {
    event.respondWith(
      caches.match('/index.html', { ignoreVary: true }).then(function (cached) {
        if (cached) return cached
        return fetch(request).catch(function () {
          return caches.match('/index.html', { ignoreVary: true }).then(function (shell) {
            return shell || Response.error()
          })
        })
      }),
    )
    return
  }

  event.respondWith(
    caches.match(request, { ignoreVary: true }).then(function (cached) {
      if (cached) return cached
      return fetch(request).then(function (response) {
        if (response.ok && RUNTIME.test(url.pathname)) {
          const copy = response.clone()
          caches.open(CACHE).then(function (cache) {
            return cache.put(request, copy)
          })
        }
        return response
      })
    }),
  )
})
`

/** The generated `sw.js`, with its build ID and install list. */
export const serviceWorkerSource = (buildId: string, precache: ReadonlyArray<string>): string =>
  SOURCE.replace(BUILD_ID, buildId).replace(PRECACHE, JSON.stringify(precache))
