//! Writes the catalog as TypeScript for `packages/simulation/src/generated`.

use crate::lower::{Catalog, Era, FieldType, MixRef, Spanned, Value};
use crate::num::Number;
use crate::num::Unit;
use std::collections::BTreeSet;
use std::fmt::Write;

pub const HEADER: &str = "// Generated by qmc from packages/simulation/content. Do not edit this file:\n\
                      // change the .qm source and run `pnpm --filter @quorum/simulation content`.\n";

fn is_ident(s: &str) -> bool {
    let mut chars = s.chars();
    chars
        .next()
        .is_some_and(|c| c.is_ascii_alphabetic() || c == '_' || c == '$')
        && chars.all(|c| c.is_ascii_alphanumeric() || c == '_' || c == '$')
}

fn string(s: &str) -> String {
    let mut out = String::from("'");
    for c in s.chars() {
        match c {
            '\\' => out.push_str("\\\\"),
            '\'' => out.push_str("\\'"),
            '\n' => out.push_str("\\n"),
            c => out.push(c),
        }
    }
    out.push('\'');
    out
}

/// An object key: bare when it is an identifier, quoted otherwise.
fn key(s: &str) -> String {
    if is_ident(s) {
        s.to_string()
    } else {
        string(s)
    }
}

fn value(v: &Value) -> String {
    match v {
        Value::Str(s) => string(s),
        Value::Num(n) => n.base().decimal().expect("checked to be a finite decimal"),
        Value::Const(name) => name.text.clone(),
        Value::Ref(path) => {
            let mut out = path[0].text.clone();
            for part in &path[1..] {
                if is_ident(&part.text) {
                    let _ = write!(out, ".{}", part.text);
                } else {
                    let _ = write!(out, "[{}]", string(&part.text));
                }
            }
            out
        }
    }
}

fn shape_value(v: &Value, ty: FieldType) -> String {
    match (v, ty) {
        (Value::Num(n), FieldType::Seconds) => n
            .in_unit(Unit::S)
            .decimal()
            .expect("seconds are a finite decimal"),
        (v, _) => value(v),
    }
}

/// The names a value reads from an import.
fn uses<'a>(v: &'a Value, out: &mut BTreeSet<&'a str>) {
    match v {
        Value::Ref(path) => {
            out.insert(&path[0].text);
        }
        Value::Const(name) => {
            out.insert(&name.text);
        }
        _ => {}
    }
}

/// The `import` lines for the names one output uses, in declaration order.
fn imports(w: &mut String, catalog: &Catalog, used: &BTreeSet<&str>) {
    for import in &catalog.imports {
        let names: Vec<&str> = import
            .names
            .iter()
            .map(|n| n.text.as_str())
            .filter(|n| used.contains(n))
            .collect();
        if !names.is_empty() {
            let _ = writeln!(
                w,
                "import {{ {} }} from {}",
                names.join(", "),
                string(&import.from)
            );
        }
    }
    let consts: Vec<&str> = catalog
        .consts
        .iter()
        .map(|c| c.export.as_str())
        .filter(|n| used.contains(n))
        .collect();
    if !consts.is_empty() {
        let _ = writeln!(
            w,
            "import {{ {} }} from './constants.ts'",
            consts.join(", ")
        );
    }
}

/// The generated module for a content file: the Effect Schema consts, the fields object a
/// Component's `(state …)` declares, and the tuples its one-of fields name.
pub fn states(
    catalog: &Catalog,
    module: &str,
) -> (Vec<(crate::data::Origin, String, bool)>, String) {
    let mut out = String::new();
    let mut needs: Vec<(crate::data::Origin, String, bool)> = Vec::new();
    let mut any = false;
    for state in catalog.states.iter().filter(|s| s.module == module) {
        any = true;
        let _ = writeln!(out);
        for field in &state.fields {
            let Some(name) = &field.values_name else {
                continue;
            };
            let values = match &field.ty {
                crate::lower::StateType::Enum(values) => values
                    .iter()
                    .map(|v| string(&v.value))
                    .collect::<Vec<_>>()
                    .join(", "),
                crate::lower::StateType::OneOf(values) => {
                    values.iter().map(num).collect::<Vec<_>>().join(", ")
                }
                crate::lower::StateType::Number | crate::lower::StateType::Bool => continue,
            };
            let _ = writeln!(out, "export const {} = [{}] as const", name.text, values);
        }
        for field in &state.fields {
            if matches!(field.ty, crate::lower::StateType::Number) {
                if let Some(name) = &field.as_name {
                    let _ = writeln!(out, "export const {} = Schema.Finite", name.text);
                    let _ = writeln!(out, "export type {} = typeof {}.Type", name.text, name.text);
                    let _ = writeln!(out);
                }
                continue;
            }
            let crate::lower::StateType::Enum(values) = &field.ty else {
                continue;
            };
            let name = field.as_name.as_ref().map_or_else(
                || crate::lower::pascal(&crate::lower::camel(&field.key.text)),
                |n| n.text.clone(),
            );
            let values = field.values_name.as_ref().map_or_else(
                || {
                    format!(
                        "[{}]",
                        values
                            .iter()
                            .map(|v| string(&v.value))
                            .collect::<Vec<_>>()
                            .join(", ")
                    )
                },
                |name| name.text.clone(),
            );
            let _ = writeln!(out, "export const {name} = Schema.Literals({values})");
            let _ = writeln!(out, "export type {name} = typeof {name}.Type");
            let _ = writeln!(out);
        }
        let object = format!("{}Fields", crate::lower::camel(&state.component.text));
        let _ = writeln!(out, "export const {object} = {{");
        for field in &state.fields {
            let key = key(&crate::lower::camel(&field.key.text));
            let base = match &field.ty {
                crate::lower::StateType::Enum(_) => field.as_name.as_ref().map_or_else(
                    || crate::lower::pascal(&crate::lower::camel(&field.key.text)),
                    |n| n.text.clone(),
                ),
                crate::lower::StateType::OneOf(_) => "Schema.Finite".to_string(),
                crate::lower::StateType::Number => field
                    .as_name
                    .as_ref()
                    .map_or_else(|| "Schema.Finite".to_string(), |n| n.text.clone()),
                crate::lower::StateType::Bool => "Schema.Boolean".to_string(),
            };
            if field.required {
                let _ = writeln!(out, "  {key}: {base},");
                continue;
            }
            let default = match &field.default.kind {
                crate::data::D::Str(s) => format!("{} as const", string(s)),
                crate::data::D::Num(n) => n.decimal().expect("checked to be a finite decimal"),
                crate::data::D::Bool(b) => b.to_string(),
                _ => continue,
            };
            let _ = writeln!(
                out,
                "  {key}: {base}.pipe(Schema.withDecodingDefaultKey(Effect.succeed({default}))),"
            );
        }
        let _ = writeln!(out, "}} as const");
    }
    if any {
        needs.push((
            crate::data::Origin::Path("effect".into()),
            "Effect".into(),
            false,
        ));
        needs.push((
            crate::data::Origin::Path("effect".into()),
            "Schema".into(),
            false,
        ));
    }
    (needs, out)
}

/// The setters a `(state …)` declares with `:only` or `:scope`. Each one is a call to
/// `fieldSetter`, so the generated file holds the field, its values, its gate, and its scope.
pub fn setters(
    catalog: &Catalog,
    module: &str,
) -> (Vec<(crate::data::Origin, String, bool)>, String) {
    let mut out = String::new();
    let mut needs: Vec<(crate::data::Origin, String, bool)> = Vec::new();
    for state in catalog.states.iter().filter(|s| s.module == module) {
        for field in &state.fields {
            if field.only.is_none() && field.scope.is_none() {
                continue;
            }
            let name = field.setter.as_ref().map_or_else(
                || {
                    format!(
                        "set{}",
                        crate::lower::pascal(&crate::lower::camel(&field.key.text))
                    )
                },
                |n| n.text.clone(),
            );
            let _ = writeln!(out, "\nexport const {name} = fieldSetter(");
            let _ = writeln!(out, "  '{}',", state.component.text);
            let _ = writeln!(out, "  '{}',", crate::lower::camel(&field.key.text));
            let _ = writeln!(out, "  {{");
            if let Some(only) = &field.only {
                let _ = writeln!(out, "    only: {},", string(&only.value));
            }
            if let Some(values) = &field.values_name {
                let _ = writeln!(out, "    values: {},", values.text);
                needs.push((
                    crate::data::Origin::Generated(format!("./{module}.ts")),
                    values.text.clone(),
                    false,
                ));
            }
            if let Some(what) = &field.values_what {
                let _ = writeln!(out, "    what: {},", string(&what.value));
            }
            if field.requires.is_some() {
                let locked = format!(
                    "{}.{}",
                    state.component.text,
                    crate::lower::camel(&field.key.text)
                );
                let _ = writeln!(out, "    locked: '{locked}',");
            }
            if field.scope.is_some() {
                let _ = writeln!(out, "    scope: 'all-of-type',");
            }
            let _ = writeln!(out, "  }},");
            let _ = writeln!(out, ")");
            needs.push((
                crate::data::Origin::Path("../action-kit.ts".into()),
                "fieldSetter".into(),
                false,
            ));
        }
    }
    (needs, out)
}

/// `GATES`: each gated setting, keyed `component.field`, with the research it needs.
fn gates(w: &mut String, catalog: &Catalog) {
    use crate::lower::GateValues;
    let _ = writeln!(
        w,
        "\nexport type GateValue = string | number | boolean\n\
         export type GateDef = Readonly<{{\n  research: ResearchId\n  what?: string\n  \
         labels?: Readonly<Record<string, Readonly<{{ name: string }}>>>\n  \
         free?: ReadonlyArray<GateValue>\n  locked?: ReadonlyArray<GateValue>\n}}>\n\
         export const GATES = {{"
    );
    for gate in &catalog.gates {
        let (key, values) = match &gate.open {
            GateValues::Free(v) => ("free", v),
            GateValues::Locked(v) => ("locked", v),
        };
        let values: Vec<String> = values.iter().map(|v| crate::data::ts(v, 0, 0)).collect();
        let label = match &gate.what {
            crate::lower::GateLabel::Text(t) => format!("what: {}", string(&t.value)),
            crate::lower::GateLabel::Table(n) => format!("labels: {}", n.text),
        };
        let _ = writeln!(
            w,
            "  {}: {{ research: {}, {label}, {key}: [{}] }},",
            string(&format!("{}.{}", gate.component.text, gate.field.text)),
            string(&gate.research.text),
            values.join(", ")
        );
    }
    let _ = writeln!(
        w,
        "}} as const satisfies Partial<\n  Record<`${{ComponentId}}.${{Extract<keyof GameNode, string>}}`, GateDef>\n>\n\
         export type GateKey = keyof typeof GATES"
    );
}

pub fn components(catalog: &Catalog) -> String {
    let mut o = String::from(HEADER);
    let w = &mut o;
    let _ = writeln!(w, "import type {{ Kind }} from '../catalog/kinds.ts'");
    let _ = writeln!(w, "import type {{ ResearchId }} from './research.ts'");
    if !catalog.gates.is_empty() {
        let _ = writeln!(w, "import type {{ GameNode }} from '../state.ts'");
    }
    // A gate's label table comes from the module that defines it.
    let scope = crate::data::Scope::new(catalog);
    for gate in &catalog.gates {
        if let crate::lower::GateLabel::Table(n) = &gate.what {
            if let Some(crate::data::Origin::Generated(p) | crate::data::Origin::Path(p)) =
                scope.value(&n.text, "components")
            {
                let _ = writeln!(w, "import {{ {} }} from '{p}'", n.text);
            }
        }
    }
    let mut used = BTreeSet::new();
    for c in &catalog.components {
        for v in [&c.name, &c.product, &c.blurb, &c.latency] {
            uses(&v.value, &mut used);
        }
    }
    imports(w, catalog, &used);
    let ids = |pick: &dyn Fn(&crate::lower::Component) -> bool| {
        catalog
            .components
            .iter()
            .filter(|c| pick(c))
            .map(|c| c.id.text.as_str())
            .collect::<Vec<_>>()
    };

    let _ = writeln!(w, "\nexport const COMPONENT_IDS = [");
    for c in &catalog.components {
        let _ = writeln!(w, "  {},", string(&c.id.text));
    }
    let _ = writeln!(
        w,
        "] as const\nexport type ComponentId = (typeof COMPONENT_IDS)[number]"
    );

    let groups = |name: &str| -> String {
        let list = if name == "BuildGroup" {
            &catalog.build_groups
        } else {
            &catalog.dock_groups
        };
        list.iter()
            .map(|g| format!("\n  | {}", string(&g.key.text)))
            .collect()
    };
    let _ = writeln!(w, "\nexport type BuildGroup ={}", groups("BuildGroup"));
    let _ = writeln!(w, "\nexport const BUILD_GROUPS: ReadonlyArray<Readonly<{{ key: BuildGroup; label: string }}>> = [");
    for g in &catalog.build_groups {
        let _ = writeln!(
            w,
            "  {{ key: {}, label: {} }},",
            string(&g.key.text),
            string(&g.label)
        );
    }
    let _ = writeln!(w, "]\n\nexport type DockGroup ={}", groups("DockGroup"));
    let _ = writeln!(w, "\nexport const DOCK_GROUPS: ReadonlyArray<\n  Readonly<{{ key: DockGroup; label: string; family: BuildGroup }}>\n> = [");
    for g in &catalog.dock_groups {
        let family = g.family.as_ref().map_or("", |f| f.text.as_str());
        let _ = writeln!(
            w,
            "  {{ key: {}, label: {}, family: {} }},",
            string(&g.key.text),
            string(&g.label),
            string(family)
        );
    }
    let _ = writeln!(
        w,
        "]\n\nexport const DOCK_OF: Readonly<Record<ComponentId, DockGroup>> = {{"
    );
    for c in &catalog.components {
        let _ = writeln!(w, "  {}: {},", key(&c.id.text), string(&c.dock.text));
    }
    let _ = writeln!(w, "}}");

    let _ = writeln!(
        w,
        "\nexport type ComponentDef = Readonly<{{\n  id: ComponentId\n  code: string\n  name: string\n  product: string\n  group: BuildGroup\n  blurb: string\n  cost: number\n  burn: number\n  sized: boolean\n  steps: number\n  latency: number\n  accepts: ReadonlyArray<Kind>\n  sends: ReadonlyArray<Kind>\n  fallback: ReadonlyArray<Kind>\n  stack: boolean\n  limiting: boolean\n  coldStart: boolean\n  maxOut: number\n  tap: boolean\n  mirror: boolean\n  control: boolean\n  unlock: ResearchId | null\n  fixed: boolean\n}}>"
    );
    let _ = writeln!(
        w,
        "\nexport const COMPONENTS: Record<ComponentId, ComponentDef> = {{"
    );
    for c in &catalog.components {
        let kinds = |l: &Option<crate::lower::KindList>| {
            format!("[{}]", list(l.iter().flat_map(|l| l.resolve(catalog))))
        };
        let latency = match &c.latency.value {
            Value::Num(n) => n
                .in_unit(Unit::Ms)
                .decimal()
                .expect("milliseconds are a finite decimal"),
            other => value(other),
        };
        let or = |n: &Option<Spanned<Number>>, default: &str| {
            n.as_ref().map_or_else(|| default.to_string(), num)
        };
        let _ = writeln!(w, "  {}: {{", key(&c.id.text));
        let _ = writeln!(w, "    id: {},", string(&c.id.text));
        let _ = writeln!(w, "    code: {},", string(&c.code.text));
        let _ = writeln!(w, "    name: {},", value(&c.name.value));
        let _ = writeln!(w, "    product: {},", value(&c.product.value));
        let _ = writeln!(w, "    group: {},", string(&c.group.text));
        let _ = writeln!(w, "    blurb: {},", value(&c.blurb.value));
        let _ = writeln!(w, "    cost: {},", num(&c.cost));
        let _ = writeln!(w, "    burn: {},", or(&c.burn, "0"));
        let _ = writeln!(w, "    sized: {},", c.has("sized"));
        let _ = writeln!(w, "    steps: {},", or(&c.steps, "1"));
        let _ = writeln!(w, "    latency: {latency},");
        let _ = writeln!(w, "    accepts: {},", kinds(&c.accepts));
        let _ = writeln!(w, "    sends: {},", kinds(&c.sends));
        let _ = writeln!(w, "    fallback: {},", kinds(&c.fallback));
        let _ = writeln!(w, "    stack: {},", c.has("stack"));
        let _ = writeln!(w, "    limiting: {},", c.has("limiting"));
        let _ = writeln!(w, "    coldStart: {},", c.has("cold-start"));
        let _ = writeln!(w, "    maxOut: {},", or(&c.max_out, "99"));
        let _ = writeln!(w, "    tap: {},", c.has("tap"));
        let _ = writeln!(w, "    mirror: {},", c.has("mirror"));
        let _ = writeln!(w, "    control: {},", c.has("control"));
        let _ = writeln!(
            w,
            "    unlock: {},",
            c.unlock
                .as_ref()
                .map_or_else(|| "null".to_string(), |u| string(&u.text))
        );
        let _ = writeln!(w, "    fixed: {},", c.has("fixed"));
        let _ = writeln!(w, "  }},");
    }
    let _ = writeln!(w, "}}");

    for (name, flag) in [
        ("TLS_TERMINATORS", "tls"),
        ("GLOBAL_COMPONENTS", "global"),
        ("ZONE_SPANNING_COMPONENTS", "zone-spanning"),
        ("STANDBY_TYPES", "standby"),
    ] {
        let _ = writeln!(
            w,
            "\nexport const {name}: ReadonlyArray<ComponentId> = [{}]",
            list(ids(&|c| c.has(flag)))
        );
    }

    let _ = writeln!(
        w,
        "\nexport const FLAT_CAPACITY: Readonly<Record<string, number>> = {{"
    );
    for c in &catalog.components {
        if let Some(capacity) = &c.capacity {
            let n = capacity
                .as_ref()
                .map_or_else(|| "Number.POSITIVE_INFINITY".to_string(), num);
            let _ = writeln!(w, "  {}: {n},", key(&c.id.text));
        }
    }
    let _ = writeln!(w, "}}");
    if !catalog.gates.is_empty() {
        gates(w, catalog);
    }
    o
}

pub fn kinds(catalog: &Catalog) -> String {
    let mut o = String::from(HEADER);
    for (name, ty, kinds) in [
        ("REQUEST_KINDS", "RequestKind", &catalog.request_kinds),
        ("BACKEND_KINDS", "BackendKind", &catalog.backend_kinds),
        ("DATA_KINDS", "DataKind", &catalog.data_kinds),
    ] {
        let _ = writeln!(o, "\nexport const {name} = [");
        for kind in kinds {
            let _ = writeln!(o, "  {},", string(&kind.text));
        }
        let _ = writeln!(o, "] as const\nexport type {ty} = (typeof {name})[number]");
    }
    o
}

pub fn constants(catalog: &Catalog) -> String {
    let mut o = String::from(HEADER);
    for c in &catalog.consts {
        let _ = writeln!(o, "export const {} = {}", c.export, num(&c.value));
    }
    o
}

fn list<'a>(items: impl IntoIterator<Item = &'a str>) -> String {
    items.into_iter().map(string).collect::<Vec<_>>().join(", ")
}

pub fn incidents(catalog: &Catalog) -> String {
    let mut o = String::from(HEADER);
    let w = &mut o;
    let _ = writeln!(
        w,
        "import type {{ RequestKind }} from '../catalog/kinds.ts'"
    );
    let _ = writeln!(w, "import type {{ ResearchId }} from './research.ts'");
    let mut used = BTreeSet::new();
    for i in &catalog.incidents {
        for v in [&i.name, &i.cause, &i.prevention] {
            uses(&v.value, &mut used);
        }
        if let Some((_, by)) = &i.surge {
            uses(&by.value, &mut used);
        }
    }
    imports(w, catalog, &used);

    let _ = writeln!(w, "\nexport const INCIDENT_IDS = [");
    for i in &catalog.incidents {
        let _ = writeln!(w, "  {},", string(&i.id.text));
    }
    let _ = writeln!(
        w,
        "] as const\nexport type IncidentId = (typeof INCIDENT_IDS)[number]"
    );

    let _ = writeln!(w, "\nexport const FALLACY_IDS = [");
    for f in &catalog.fallacies {
        let _ = writeln!(w, "  {},", string(&f.text));
    }
    let _ = writeln!(
        w,
        "] as const\nexport type FallacyId = (typeof FALLACY_IDS)[number]"
    );

    let _ = writeln!(
        w,
        "\nexport const FALLACY_INCIDENTS: Readonly<Record<FallacyId, IncidentId>> = {{"
    );
    for f in &catalog.fallacies {
        let teacher = catalog
            .incidents
            .iter()
            .find(|i| i.fallacy.as_ref().is_some_and(|x| x.text == f.text))
            .expect("checked");
        let _ = writeln!(w, "  {}: {},", key(&f.text), string(&teacher.id.text));
    }
    let _ = writeln!(w, "}}");

    let _ = writeln!(
        w,
        "\nexport type IncidentDef = Readonly<{{\n  id: IncidentId\n  name: string\n  era: number\n  severity: 1 | 2 | 3\n  escalatesTo: 1 | 2 | null\n  duration: number\n  cause: string\n  prevention: string\n  actions: ReadonlyArray<ResearchId>\n}}>"
    );

    let _ = writeln!(w, "\nexport const KIND_SURGE: Partial<Record<IncidentId, readonly [RequestKind, number]>> = {{");
    for i in &catalog.incidents {
        if let Some((kind, by)) = &i.surge {
            let _ = writeln!(
                w,
                "  {}: [{}, {}],",
                key(&i.id.text),
                string(&kind.text),
                value(&by.value)
            );
        }
    }
    let _ = writeln!(w, "}}");

    let _ = writeln!(
        w,
        "\nexport const RUNTIME_INCIDENT_FAILURES: Partial<Record<IncidentId, number>> = {{"
    );
    for i in &catalog.incidents {
        if let Some(share) = &i.failures {
            let _ = writeln!(w, "  {}: {},", key(&i.id.text), num(share));
        }
    }
    let _ = writeln!(w, "}}");

    let _ = writeln!(
        w,
        "\nexport const CASCADES: Partial<Record<IncidentId, IncidentId>> = {{"
    );
    for i in &catalog.incidents {
        if let Some(next) = &i.cascades {
            let _ = writeln!(w, "  {}: {},", key(&i.id.text), string(&next.text));
        }
    }
    let _ = writeln!(w, "}}");

    let _ = writeln!(
        w,
        "\nexport const INCIDENTS: Record<IncidentId, IncidentDef> = {{"
    );
    for i in &catalog.incidents {
        let escalates = i
            .escalates_to
            .as_ref()
            .map_or_else(|| "null".to_string(), num);
        let seconds = i
            .duration
            .value
            .in_unit(Unit::S)
            .decimal()
            .expect("seconds are a finite decimal");
        let _ = writeln!(w, "  {}: {{", key(&i.id.text));
        let _ = writeln!(w, "    id: {},", string(&i.id.text));
        let _ = writeln!(w, "    name: {},", value(&i.name.value));
        let era = catalog
            .era_index(&i.era.value.text)
            .expect("check rejects unknown Eras");
        let _ = writeln!(w, "    era: {era},");
        let _ = writeln!(w, "    severity: {},", num(&i.severity));
        let _ = writeln!(w, "    escalatesTo: {escalates},");
        let _ = writeln!(w, "    duration: {seconds},");
        let _ = writeln!(w, "    cause: {},", value(&i.cause.value));
        let _ = writeln!(w, "    prevention: {},", value(&i.prevention.value));
        let _ = writeln!(
            w,
            "    actions: [{}],",
            list(i.actions.iter().map(|a| a.text.as_str()))
        );
        let _ = writeln!(w, "  }},");
    }
    let _ = writeln!(w, "}}");
    o
}

fn mix_name(name: &str) -> String {
    format!("{}_MIX", name.to_uppercase().replace('-', "_"))
}

fn num(n: &Spanned<Number>) -> String {
    value(&Value::Num(n.value))
}

/// The generated type aliases. They live in one module so a `:type` name can be imported wherever
/// it is used.
pub fn types(catalog: &Catalog) -> String {
    let scope = crate::data::Scope::new(catalog);
    let mut needs: Vec<(crate::data::Origin, String, bool)> = Vec::new();
    for ty in &catalog.type_defs {
        for (word, is_value) in crate::data::type_names(&ty.ty) {
            let origin = if is_value {
                scope
                    .value(&word, "types")
                    .or_else(|| scope.ty(&word, "types"))
            } else {
                scope.ty(&word, "types")
            };
            if let Some(origin) = origin {
                if origin != crate::data::Origin::Local
                    && !needs.iter().any(|(o, n, _)| o == &origin && n == &word)
                {
                    needs.push((origin, word, true));
                }
            }
        }
    }
    let mut body = String::new();
    for ty in &catalog.type_defs {
        let _ = writeln!(body, "export type {} = {}", ty.name.text, ty.ty);
    }
    let mut out = crate::data::merge_imports(HEADER, &needs);
    out.push_str(&body);
    out
}

pub fn eras(catalog: &Catalog) -> String {
    let mut o = String::from(HEADER);
    let w = &mut o;
    let _ = writeln!(
        w,
        "import type {{ RequestKind }} from '../catalog/kinds.ts'"
    );
    let mut used = BTreeSet::new();
    for era in &catalog.eras {
        for v in [&era.name, &era.question, &era.arrivals] {
            uses(&v.value, &mut used);
        }
    }
    imports(w, catalog, &used);
    let _ = writeln!(
        w,
        "\nexport type EraDef = Readonly<{{\n  name: string\n  market: number\n  raiseAt: number\n  grant: number\n  dilution: number\n  growth: number\n  apdexTarget: number\n  costIndex: number\n  salaryIndex: number\n  slo: number\n  incidentInterval: number\n  maxSeverity: 1 | 2 | 3\n  mix: Partial<Record<RequestKind, number>>\n  question: string\n  arrivals: string\n}}>"
    );
    for mix in &catalog.mixes {
        let name = mix.name.as_ref().expect("top-level mixes are named");
        let _ = writeln!(
            w,
            "\nexport const {}: Partial<Record<RequestKind, number>> = {{",
            mix_name(&name.text)
        );
        for (kind, share) in &mix.shares {
            let _ = writeln!(w, "  {}: {},", key(&kind.text), num(share));
        }
        let _ = writeln!(w, "}}");
    }
    let _ = writeln!(w, "\nexport const ERAS: ReadonlyArray<EraDef> = [");
    for era in &catalog.eras {
        era_entry(w, era);
    }
    let _ = writeln!(w, "]");
    o
}

fn era_entry(w: &mut String, era: &Era) {
    let _ = writeln!(w, "  {{");
    let _ = writeln!(w, "    name: {},", value(&era.name.value));
    let _ = writeln!(w, "    market: {},", num(&era.market));
    let raise = era
        .raise_at
        .as_ref()
        .map_or_else(|| "Number.POSITIVE_INFINITY".to_string(), num);
    let _ = writeln!(w, "    raiseAt: {raise},");
    let _ = writeln!(w, "    grant: {},", num(&era.grant));
    let _ = writeln!(w, "    dilution: {},", num(&era.dilution));
    let _ = writeln!(w, "    growth: {},", num(&era.growth));
    let _ = writeln!(w, "    apdexTarget: {},", num(&era.apdex_target));
    let _ = writeln!(w, "    costIndex: {},", num(&era.cost_index));
    let _ = writeln!(w, "    salaryIndex: {},", num(&era.salary_index));
    let _ = writeln!(w, "    slo: {},", num(&era.slo));
    let every = era.incident_every.as_ref().map_or_else(
        || "0".to_string(),
        |n| {
            n.value
                .in_unit(Unit::S)
                .decimal()
                .expect("seconds are a finite decimal")
        },
    );
    let _ = writeln!(w, "    incidentInterval: {every},");
    let _ = writeln!(w, "    maxSeverity: {},", num(&era.max_severity));
    let mix = match &era.mix {
        MixRef::Named(name) => mix_name(&name.text),
        MixRef::Inline(mix) => {
            let fields: Vec<String> = mix
                .shares
                .iter()
                .map(|(k, s)| format!("{}: {}", key(&k.text), num(s)))
                .collect();
            format!("{{ {} }}", fields.join(", "))
        }
    };
    let _ = writeln!(w, "    mix: {mix},");
    let _ = writeln!(w, "    question: {},", value(&era.question.value));
    let _ = writeln!(w, "    arrivals: {},", value(&era.arrivals.value));
    let _ = writeln!(w, "  }},");
}

pub fn research(catalog: &Catalog) -> String {
    let mut o = String::from(HEADER);
    let w = &mut o;
    let _ = writeln!(
        w,
        "import type {{ InsightPool }} from '../catalog/kinds.ts'"
    );
    let _ = writeln!(
        w,
        "import type {{ FrameworkId }} from '../catalog/runtimes.ts'"
    );
    let mut used = BTreeSet::new();
    for r in &catalog.research {
        uses(&r.name.value, &mut used);
        uses(&r.blurb.value, &mut used);
        for (_, v) in r.shape.iter().flat_map(|s| &s.fields) {
            uses(&v.value, &mut used);
        }
    }
    imports(w, catalog, &used);
    let _ = writeln!(w, "\nexport const RESEARCH_IDS = [");
    for r in &catalog.research {
        let _ = writeln!(w, "  {},", string(&r.id.text));
    }
    let _ = writeln!(
        w,
        "] as const\nexport type ResearchId = (typeof RESEARCH_IDS)[number]\n"
    );

    let _ = writeln!(w, "export type ResearchTrack =");
    for t in &catalog.tracks {
        let _ = writeln!(w, "  | {}", string(&t.key.text));
    }
    let _ = writeln!(w, "\nexport const RESEARCH_TRACKS: ReadonlyArray<Readonly<{{ key: ResearchTrack; label: string }}>> = [");
    for t in &catalog.tracks {
        let _ = writeln!(
            w,
            "  {{ key: {}, label: {} }},",
            string(&t.key.text),
            string(&t.label)
        );
    }
    let _ = writeln!(w, "]\n");

    let _ = writeln!(
        w,
        "export type ResearchDef = Readonly<{{\n  id: ResearchId\n  name: string\n  track: ResearchTrack\n  cost: number\n  era: number\n  requires: ReadonlyArray<ResearchId>\n  blurb: string\n}}>\n"
    );
    let _ = writeln!(
        w,
        "export const RESEARCH_LIST: ReadonlyArray<ResearchDef> = ["
    );
    for r in &catalog.research {
        let requires = r
            .requires
            .iter()
            .map(|q| string(&q.text))
            .collect::<Vec<_>>()
            .join(", ");
        let _ = writeln!(w, "  {{");
        let _ = writeln!(w, "    id: {},", string(&r.id.text));
        let _ = writeln!(w, "    name: {},", value(&r.name.value));
        let _ = writeln!(w, "    track: {},", string(&r.track.text));
        let _ = writeln!(w, "    cost: {},", r.cost.value.value);
        let era = catalog
            .era_index(&r.era.value.text)
            .expect("check rejects unknown Eras");
        let _ = writeln!(w, "    era: {era},");
        let _ = writeln!(w, "    requires: [{requires}],");
        let _ = writeln!(w, "    blurb: {},", value(&r.blurb.value));
        let _ = writeln!(w, "  }},");
    }
    let _ = writeln!(w, "]\n");

    let _ = writeln!(
        w,
        "/** The Insight pools a study draws on, when they differ from its Era's. */"
    );
    let _ = writeln!(w, "export const RESEARCH_INSIGHT: Partial<Record<ResearchId, ReadonlyArray<InsightPool>>> = {{");
    for r in &catalog.research {
        if let Some((_, pools)) = &r.insight {
            let pools = pools
                .iter()
                .map(|p| string(&p.text))
                .collect::<Vec<_>>()
                .join(", ");
            let _ = writeln!(w, "  {}: [{pools}],", key(&r.id.text));
        }
    }
    let _ = writeln!(w, "}}\n");

    let _ = writeln!(w, "export type StudyShape =");
    for kind in &catalog.shape_kinds {
        let mut fields = format!("readonly kind: {}", string(&kind.name.text));
        for (name, _) in &kind.fields {
            let _ = write!(
                fields,
                "; readonly {}: number",
                crate::lower::camel(&name.text)
            );
        }
        let _ = writeln!(w, "  | Readonly<{{ {fields} }}>");
    }
    let _ = writeln!(w, "\nexport const STUDY_SHAPE_KINDS = [");
    for kind in &catalog.shape_kinds {
        let _ = writeln!(w, "  {},", string(&kind.name.text));
    }
    let _ = writeln!(
        w,
        "] as const\nexport type StudyShapeKind = (typeof STUDY_SHAPE_KINDS)[number]\n"
    );

    let _ = writeln!(
        w,
        "export const SHAPE: Partial<Record<ResearchId, StudyShape>> = {{"
    );
    for r in &catalog.research {
        let Some(shape) = &r.shape else { continue };
        let kind = catalog
            .shape_kinds
            .iter()
            .find(|k| k.name.text == shape.kind.text)
            .expect("checked");
        let mut fields = format!("kind: {}", string(&kind.name.text));
        for (name, ty) in &kind.fields {
            let (_, v) = shape
                .fields
                .iter()
                .find(|(n, _)| n.text == name.text)
                .expect("checked");
            let _ = write!(
                fields,
                ", {}: {}",
                crate::lower::camel(&name.text),
                shape_value(&v.value, *ty)
            );
        }
        let _ = writeln!(w, "  {}: {{ {fields} }},", key(&r.id.text));
    }
    let _ = writeln!(w, "}}\n");

    for (name, pick) in [
        (
            "BREADTH",
            (|r| r.breadth.as_ref())
                as fn(
                    &crate::lower::Research,
                ) -> Option<&crate::lower::Spanned<crate::num::Number>>,
        ),
        ("REGION_BREADTH", |r| r.region_breadth.as_ref()),
    ] {
        let _ = writeln!(
            w,
            "export const {name}: Partial<Record<ResearchId, number>> = {{"
        );
        for r in &catalog.research {
            if let Some(n) = pick(r) {
                let _ = writeln!(w, "  {}: {},", key(&r.id.text), n.value.value);
            }
        }
        let _ = writeln!(w, "}}\n");
    }

    let _ = writeln!(w, "/** The research that unlocks each framework. */");
    let _ = writeln!(w, "export const FRAMEWORK_UNLOCKS = {{");
    for r in &catalog.research {
        if let Some(fw) = &r.unlocks_framework {
            let _ = writeln!(w, "  {}: {},", key(&fw.text), string(&r.id.text));
        }
    }
    let _ = writeln!(
        w,
        "}} as const satisfies Partial<Record<FrameworkId, ResearchId>>"
    );
    o
}

