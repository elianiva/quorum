export const colorOf = (look: Look): string =>
  'component' in look
    ? `var(--group-${COMPONENTS[look.component].group})`
    : 'glyph' in look
      ? `oklch(0.62 0.15 ${look.hue})`
      : 'logo' in look
        ? (STACK_LOGOS[look.logo].color ?? 'var(--foreground)')
        : look.brand.color

